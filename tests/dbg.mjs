import { launch, open, clear } from './harness.mjs';
const b = await launch();
const { page, errors } = await open(b, { w: 900, h: 640 });
await clear(page);
await page.keyboard.press('KeyM'); await page.waitForTimeout(500);
await page.evaluate(() => document.querySelector('.modal .x').click()); await page.waitForTimeout(400);
console.log('after click', await page.evaluate(() => [...document.querySelectorAll('.modal')].map(m => m.className)), errors);
await page.keyboard.press('KeyM'); await page.waitForTimeout(500);
console.log('reopen', await page.evaluate(() => [!!document.querySelector('.pad'), __sv.paused]));
await b.close();
